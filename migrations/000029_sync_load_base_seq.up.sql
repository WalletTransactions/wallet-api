-- Загрузка с нуля после чистки tombstone (change purge-synced-tombstones,
-- исправление после ручной проверки на test 2026-11-04).
--
-- Устройство, которое грузит поток с курсора 0, идёт по страницам, и его
-- промежуточный курсор (граница страницы, например 13) может быть меньше
-- change_stream.purged_seq (например 77). Правило «0 < cursor < purged_seq
-- -> reset "purged"» отправляло такое устройство снова на 0 — загрузка
-- зацикливалась: новые установки, старые клиенты и любой телефон после
-- сброса не могли догрузить поток.
--
-- *_load_base_seq — purged_seq потока в момент последнего pull этого
-- устройства с курсором 0 (в том числе после сброса). Пока purged_seq потока
-- не вырос с тех пор, курсор ниже него — честная загрузка с нуля, а не
-- отставание: удалённое ДО начала загрузки ей не нужно. Вырасти purged_seq
-- мимо курсора активного устройства не может — его подтверждение держит
-- горизонт; вырос — устройство выпадало (дольше срока без pull), и сброс
-- снова верен. NULL — устройство с нуля не грузилось (или сменило леджер).
ALTER TABLE device
    ADD COLUMN ledger_load_base_seq    bigint,
    ADD COLUMN reference_load_base_seq bigint;

COMMENT ON COLUMN device.ledger_load_base_seq IS
    'purged_seq потока леджера в момент последнего GET /sync/pull этого устройства с ledger_seq = 0 (или сброса). Пока purged_seq не вырос, курсор ниже него не даёт reset "purged" — загрузка с нуля идёт по страницам. NULL — с нуля не грузилось или сменило леджер.';
COMMENT ON COLUMN device.reference_load_base_seq IS
    'То же для потока справочников (reference_seq = 0).';

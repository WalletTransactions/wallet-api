-- Выдача очередного номера версии в потоке изменений.
--
-- Вызывается один раз на батч записи, внутри той же транзакции, что и сами
-- изменения. Все строки батча получают один и тот же seq — на этом держится
-- гарантия, что страница выборки изменений не разрежет атомарную группу
-- (см. ../README.md, раздел «Курсор и страницы»).
--
-- UPDATE берёт блокировку строки потока, поэтому писатели одного леджера
-- выстраиваются в очередь и порядок seq совпадает с порядком коммитов.
-- Именно это отличает счётчик от SEQUENCE: у последовательности номер выдаётся
-- вне транзакции, и seq = 5 может закоммититься раньше, чем seq = 4 — читатель,
-- идущий по курсору, в этот момент молча потеряет строку.
--
-- Записи в один леджер редки (одно-два устройства пользователя), так что
-- сериализация писателей здесь ничего не стоит.
CREATE FUNCTION next_seq(p_stream uuid) RETURNS bigint
    LANGUAGE sql
AS $$
    UPDATE change_stream
       SET seq = seq + 1
     WHERE id = p_stream
    RETURNING seq;
$$;

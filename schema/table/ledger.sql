-- Леджер — единица владения данными и единица синхронизации: всё, что
-- пользователь видит в приложении, принадлежит ровно одному леджеру.
--
-- Отдельная сущность, а не user_id в каждой таблице, ради общего кошелька на
-- несколько человек (ledger_member). Задним числом это не переделывается: смена
-- ключа арендатора означает переписывание каждой таблицы и каждого индекса.
--
-- id одновременно является идентификатором собственного потока изменений —
-- строки в change_stream с тем же id и kind = 'ledger'. Создание леджера
-- поэтому всегда две вставки в одной транзакции, сначала в change_stream.
--
-- ON DELETE RESTRICT: удаление леджера не должно оставить осиротевший поток —
-- сначала снимается леджер со всеми данными (каскадом от ledger_id), затем
-- его строка в change_stream.
CREATE TABLE ledger (
    id         uuid PRIMARY KEY REFERENCES change_stream (id) ON DELETE RESTRICT,
    name       text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE ledger IS
    'Леджер — единица владения данными и единица синхронизации: всё, что видит пользователь, принадлежит ровно одному леджеру.';
COMMENT ON COLUMN ledger.id IS
    'Совпадает с change_stream.id того же потока (kind=''ledger'') — создание леджера всегда две вставки в одной транзакции, сначала в change_stream.';
COMMENT ON COLUMN ledger.name IS
    'Название леджера, для показа в UI при выборе/переключении. На MVP — один леджер на пользователя, поле зарезервировано на будущий шаринг.';
COMMENT ON COLUMN ledger.created_at IS 'Момент создания леджера.';

-- Двоичное содержимое, адресуемое по SHA-256. Сейчас это только изображения
-- иконок (WEBP 256x256, см. icon.sql).
--
-- Зачем отдельно от icon: одинаковая картинка у разных пользователей хранится
-- один раз, а клиент по хешу заранее знает, что этот файл у него уже есть, и не
-- качает его повторно. При синке через мобильный интернет это основная экономия
-- трафика — всё остальное в протоколе это JSON на сотни байт.
--
-- Строки namеренно ничьи: ledger_id здесь нет, содержимое общее. Право прочитать
-- конкретный blob проверяет приложение — по наличию icon с этим content_sha256,
-- видимой запрашивающему леджеру. В схеме этой проверки нет и быть не может:
-- у контент-адресуемого хранилища владельца не существует.
--
-- Ограничение размера — защита от заливки произвольных файлов через API иконок.
-- Иконка приложения весит десятки килобайт, мегабайт с запасом.
CREATE TABLE blob (
    sha256     bytea PRIMARY KEY CHECK (octet_length(sha256) = 32),
    bytes      bytea       NOT NULL CHECK (octet_length(bytes) BETWEEN 1 AND 1048576),
    created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE blob IS
    'Двоичное содержимое, адресуемое по SHA-256 (сейчас только изображения иконок). Строки ничьи — ledger_id здесь нет, содержимое общее; право прочитать конкретный blob проверяет приложение.';
COMMENT ON COLUMN blob.sha256 IS
    'SHA-256 содержимого, ровно 32 байта — первичный ключ и адрес контента одновременно.';
COMMENT ON COLUMN blob.bytes IS
    'Само содержимое (WEBP-изображение иконки), от 1 байта до 1 МиБ — верхняя граница защищает от заливки произвольных файлов через API иконок.';
COMMENT ON COLUMN blob.created_at IS 'Момент заливки содержимого.';
